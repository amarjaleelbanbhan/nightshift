import type { Command } from "commander";
import { failWith } from "../ui/feedback.js";

/**
 * `nightshift completion powershell` - a Tab-completion script for the shell this product
 * actually targets.
 *
 * Why this exists at all: several of NIGHTSHIFT's arguments are values a human cannot
 * reasonably type. A backup id is `1794752118976-c615f1f6`, and `restore <backupId>` is the
 * documented way to undo a theme apply, so the recovery path currently requires hand-copying a
 * millisecond timestamp and eight hex characters off a table (#30).
 *
 * PowerShell only, deliberately. Windows is the only supported platform
 * (`docs/PLATFORM-COMPATIBILITY.md`) and PowerShell is Windows Terminal's default shell;
 * shipping bash and zsh scripts would imply support the product disclaims (#19).
 *
 * Two constraints shape everything below.
 *
 * - **Nothing is hardcoded.** The command, subcommand and option table is generated by walking
 *   the live Commander tree, and the values come from the live registries through
 *   `completion values`. A hardcoded theme list goes stale the moment a user adds a theme, and
 *   a hardcoded command list goes stale the moment someone adds a command - silently, in a file
 *   nobody opens again.
 * - **Latency.** This runs on every Tab press, so `completion` itself is print-and-exit and its
 *   static import graph is deliberately tiny: no zod, no boxen, no `@clack/prompts`, no
 *   `cli-table3` (asserted by `tests/integration/completion.test.ts`). The registry imports in
 *   `completionValues` are dynamic for the same reason - emitting the script must not pay for
 *   reading themes, and vice versa. Measured costs are in `docs/development/`-style terms in
 *   the README section this command documents.
 *
 * Font-family completion is omitted, not forgotten: `detectInstalledFonts()` parses every font
 * file in both font directories (~1.5 s), and a Tab press that takes a second and a half is
 * worse than no completion. `findInstalledFont` cannot help - completion needs the whole list,
 * which is exactly the case its early exit does not cover.
 */

/** The registries completion can read ids from. */
export type CompletionValueKind = "theme" | "profile" | "backup";

const VALUE_KINDS = new Set<string>(["theme", "profile", "backup"]);

/** One node of the generated completion table: a command path and what may follow it. */
interface CompletionNode {
  /** Space-joined command path, `""` for the root. */
  path: string;
  subcommands: string[];
  options: string[];
  /** The registry its positional argument draws from, when it draws from one. */
  values: CompletionValueKind | null;
}

/**
 * Which registry a command's first positional argument accepts.
 *
 * Derived from the argument's own name rather than from a list of command paths, so a new
 * `theme <verb> <id>` gets completion for free and a command taking a `<file>` or a `<family>`
 * never offers theme ids. If a future argument is named something else it gets no completion,
 * which is the safe direction to fail in.
 */
function valueKindFor(path: string[], argumentName: string): CompletionValueKind | null {
  if (argumentName === "backupId") return "backup";
  if (argumentName !== "id") return null;
  const group = path[0];
  return group === "theme" || group === "profile" ? group : null;
}

/** Flattens the Commander tree into one node per command path. Reads nothing off disk. */
export function collectCompletionNodes(program: Command): CompletionNode[] {
  const nodes: CompletionNode[] = [];

  const visit = (command: Command, path: string[]): void => {
    const [firstArgument] = command.registeredArguments;
    nodes.push({
      path: path.join(" "),
      subcommands: command.commands.map((c) => c.name()),
      // `--help` is real on every command but is not registered as an Option, so it is added
      // here; a user tabbing for options expects to see it.
      options: [
        ...command.options.filter((o) => !o.hidden).map((o) => o.long ?? o.short ?? o.flags),
        "--help",
      ],
      values: firstArgument ? valueKindFor(path, firstArgument.name()) : null,
    });
    for (const child of command.commands) visit(child, [...path, child.name()]);
  };

  visit(program, []);
  return nodes;
}

/** PowerShell single-quoted string literal. */
function psString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function psArray(values: string[]): string {
  return values.length === 0 ? "@()" : `@(${values.map(psString).join(", ")})`;
}

/**
 * The completion script itself.
 *
 * The completer resolves the command path by walking known subcommands from the root and
 * stopping at the first word that is not one, which is what makes it behave correctly after a
 * value has already been typed (`nightshift theme apply redline --<TAB>` still offers
 * `theme apply`'s options). Options are offered only once the user has typed a `-`, so no
 * process is spawned for them.
 */
export function powershellCompletionScript(program: Command): string {
  const table = collectCompletionNodes(program)
    .map(
      (node) =>
        `  ${psString(node.path)} = @{ Sub = ${psArray(node.subcommands)}; ` +
        `Opt = ${psArray(node.options)}; Val = ${node.values ? psString(node.values) : "''"} }`,
    )
    .join("\n");

  return `# NIGHTSHIFT completion for PowerShell.
# Generated by \`nightshift completion powershell\` - re-generate it after upgrading NIGHTSHIFT.

$NightshiftCompletions = @{
${table}
}

Register-ArgumentCompleter -Native -CommandName nightshift -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    $typed = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })
    if ($wordToComplete -and $typed.Count -gt 0 -and $typed[-1] -eq $wordToComplete) {
        $typed = @($typed | Select-Object -First ($typed.Count - 1))
    }

    $path = ''
    foreach ($word in $typed) {
        if ($word.StartsWith('-')) { continue }
        $next = if ($path) { "$path $word" } else { $word }
        if ($NightshiftCompletions.ContainsKey($next)) { $path = $next } else { break }
    }

    $node = $NightshiftCompletions[$path]
    if (-not $node) { return }

    if ($wordToComplete.StartsWith('-')) {
        # Options only, and no process spawned: a user typing a dash does not want theme ids.
        $candidates = $node.Opt
    } else {
        $candidates = @($node.Sub)
        if ($node.Val) {
            # The ids come from the live registries, so a theme the user added a moment ago
            # completes. Failures are swallowed: a broken config must not break the prompt.
            $candidates += @(nightshift completion values $node.Val 2>$null)
        }
        # Options are included on an empty word because PowerShell never invokes a native
        # completer for a bare '-' or '--' (verified: its own completers behave identically), so
        # this is the only Tab press that can surface a flag like --dry-run.
        $candidates += $node.Opt
    }

    $candidates | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
        $quoted = if ($_ -match '\\s') { "'$_'" } else { $_ }
        [System.Management.Automation.CompletionResult]::new($quoted, $_, 'ParameterValue', $_)
    }
}
`;
}

/**
 * Ids from the live registries, one kind per call.
 *
 * The imports are dynamic because each registry drags zod in behind it (~230 ms) and the two
 * callers need different ones: emitting the script needs neither, and a Tab press needs exactly
 * one. Returns null for an unknown kind so the caller can report it with a usage error rather
 * than an empty list that looks like "no themes".
 */
export async function completionValues(kind: string): Promise<string[] | null> {
  switch (kind) {
    case "theme": {
      const { listThemes } = await import("../../core/themes/registry.js");
      return listThemes().map((entry) => entry.theme.id);
    }
    case "profile": {
      const { listProfiles } = await import("../../core/profiles/registry.js");
      return listProfiles().map((entry) => entry.profile.id);
    }
    case "backup": {
      const { listBackups } = await import("../../backup/manager.js");
      return listBackups().map((backup) => backup.id);
    }
    default:
      return null;
  }
}

export function runCompletionPowerShell(program: Command): void {
  console.log(powershellCompletionScript(program));
}

export async function runCompletionValues(kind: string): Promise<void> {
  const values = await completionValues(kind);
  if (values === null) {
    failWith(
      `Unknown completion value kind "${kind}".`,
      `Expected one of: ${[...VALUE_KINDS].join(", ")}.`,
    );
    return;
  }
  // One id per line and nothing else - this is read by the generated script, not by a person.
  if (values.length > 0) console.log(values.join("\n"));
}

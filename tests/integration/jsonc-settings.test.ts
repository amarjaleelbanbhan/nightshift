import { describe, it, expect, beforeEach, afterEach } from "vitest";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { applyThemeFileOnly } from "../../src/core/themes/apply.js";
import { readWindowsTerminalSettings } from "../../src/adapters/windows-terminal/apply.js";

/**
 * `theme apply` against the settings.json Windows Terminal actually ships: JSONC, with a
 * generated comment header, hand-written annotations, trailing commas and the user's own
 * indentation (#14).
 *
 * This file exists because the previous implementation had exactly two possible behaviours for
 * such a file and both were wrong - refuse it (so the command was unusable for anyone who had
 * annotated their settings) or round-trip it through `JSON.stringify` (which would silently
 * delete every comment, the same defect class as the legacy-`profiles` bug this project
 * already fixed). So what is pinned here is not that the write succeeds, but that the bytes
 * the user wrote and NIGHTSHIFT did not ask about are still there afterwards.
 */

const WT = ["Packages", "Microsoft.WindowsTerminal_8wekyb3d8bbwe", "LocalState"];

/** Two-space indented, LF, commented, with a trailing comma - none of it NIGHTSHIFT's choice. */
const COMMENTED_SETTINGS = `// This file was initially generated by Windows Terminal 1.21
// Edit it with care.
{
  "$help": "https://aka.ms/terminal-documentation",
  "defaultProfile": "{some-guid}",
  /* I turned this on deliberately. */
  "copyOnSelect": true,
  "profiles": {
    "defaults": {
      "useAcrylic": true // looks better over my wallpaper
    },
    "list": [
      {
        "name": "PowerShell",
        "guid": "{some-guid}"
      }
    ]
  },
  "schemes": [
    // my own scheme, do not touch
    {
      "name": "Campbell",
      "background": "#0C0C0C"
    },
  ]
}
`;

describe("theme apply against a JSONC settings.json", () => {
  let tmpRoot: string;
  let settingsPath: string;
  let originalLocalAppData: string | undefined;
  let originalAppData: string | undefined;

  function write(content: string): void {
    fs.writeFileSync(settingsPath, content);
  }

  function read(): string {
    return fs.readFileSync(settingsPath, "utf8");
  }

  beforeEach(() => {
    tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), "nightshift-jsonc-"));
    const localAppData = path.join(tmpRoot, "LocalAppData");
    settingsPath = path.join(localAppData, ...WT, "settings.json");
    fs.mkdirSync(path.dirname(settingsPath), { recursive: true });
    write(COMMENTED_SETTINGS);

    originalLocalAppData = process.env.LOCALAPPDATA;
    originalAppData = process.env.APPDATA;
    process.env.LOCALAPPDATA = localAppData;
    process.env.APPDATA = path.join(tmpRoot, "AppData");
  });

  afterEach(() => {
    process.env.LOCALAPPDATA = originalLocalAppData;
    process.env.APPDATA = originalAppData;
    fs.rmSync(tmpRoot, { recursive: true, force: true });
  });

  it("applies the theme instead of refusing the file", () => {
    const result = applyThemeFileOnly("ghost-protocol");

    expect(result.ok).toBe(true);
    const written = readWindowsTerminalSettings(settingsPath);
    const profiles = written.profiles as Record<string, unknown>;
    expect((profiles.defaults as Record<string, unknown>).colorScheme).toBe("Ghost Protocol");
    expect((written.schemes as { name: string }[]).map((s) => s.name)).toEqual([
      "Campbell",
      "Ghost Protocol",
    ]);
  });

  it("creates profiles.defaults.font from nothing, with both of its keys", () => {
    // The fixture has no `font` key, so this is the text edit that has to synthesise two
    // levels of nested object. Asserted after a real write rather than off the object merge:
    // a wrong key path (`profiles.default.font`) or a swapped face/size would be invisible in
    // the merge, which never touches the file.
    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);

    const defaults = (readWindowsTerminalSettings(settingsPath).profiles as Record<string, unknown>)
      .defaults as Record<string, unknown>;
    expect(defaults.font).toEqual({ face: "Cascadia Code", size: 14 });
    // The key it was added next to is still there and still itself.
    expect(defaults.useAcrylic).toBe(true);
  });

  it("applies to a minified single-line settings.json", () => {
    // Nothing indented to learn the indentation from, which is `detectFormatting`'s fallback
    // branch. A real file: anyone who has ever run their settings.json through a formatter
    // that strips whitespace, or generated it from a script.
    write('{"copyOnSelect":true,"profiles":{"defaults":{}},"schemes":[]}');

    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);
    const written = readWindowsTerminalSettings(settingsPath);
    expect(written.copyOnSelect).toBe(true);
    expect((written.schemes as { name: string }[]).map((s) => s.name)).toEqual(["Ghost Protocol"]);
    // With no line endings anywhere, jsonc-parser's formatter expands its edit range to the
    // nearest EOL in each direction and so reaches both ends of the file - a minified file is
    // the one case that comes back pretty-printed as a whole, at the 4-space fallback. Pinned
    // because it is the documented exception to "the rest of the file is untouched", not an
    // accident: values survive, whitespace does not.
    expect(read()).toContain('\n    "copyOnSelect"');
  });

  it("creates `schemes` when the file has no such key at all", () => {
    write('{\n  // just this\n  "copyOnSelect": true\n}');

    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);
    expect(read()).toContain("// just this");
    expect(
      (readWindowsTerminalSettings(settingsPath).schemes as { name: string }[]).map((s) => s.name),
    ).toEqual(["Ghost Protocol"]);
  });

  it("keeps every comment the user wrote", () => {
    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);

    const after = read();
    for (const comment of [
      "// This file was initially generated by Windows Terminal 1.21",
      "// Edit it with care.",
      "/* I turned this on deliberately. */",
      "// looks better over my wallpaper",
      "// my own scheme, do not touch",
    ]) {
      expect(after).toContain(comment);
    }
  });

  it("keeps the file's own key order and indentation", () => {
    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);

    const after = read();
    // Key order: a JSON.stringify round trip rebuilt the object and could not have kept
    // `$help` first, nor `copyOnSelect` ahead of `profiles`.
    expect(after.indexOf('"$help"')).toBeLessThan(after.indexOf('"defaultProfile"'));
    expect(after.indexOf('"copyOnSelect"')).toBeLessThan(after.indexOf('"profiles"'));
    // Indentation: the file is 2-space, and the write must not reindent it to 4.
    expect(after).toContain('\n  "copyOnSelect"');
    expect(after).not.toContain('\n    "copyOnSelect"');
  });

  it("preserves unrelated values, including the user's own scheme", () => {
    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);

    const written = readWindowsTerminalSettings(settingsPath);
    expect(written.$help).toBe("https://aka.ms/terminal-documentation");
    expect(written.copyOnSelect).toBe(true);
    const profiles = written.profiles as Record<string, unknown>;
    expect((profiles.defaults as Record<string, unknown>).useAcrylic).toBe(true);
    expect(profiles.list).toEqual([{ name: "PowerShell", guid: "{some-guid}" }]);
    const campbell = (written.schemes as Record<string, unknown>[]).find(
      (s) => s.name === "Campbell",
    );
    expect(campbell?.background).toBe("#0C0C0C");
  });

  it("re-applying the same theme changes nothing further", () => {
    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);
    const once = read();
    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);
    // Not merely "still valid": byte-identical. An edit that re-expanded, re-indented or
    // re-appended on every run would drift a file NIGHTSHIFT does not own a little each time.
    expect(read()).toBe(once);
  });

  it("replaces the existing entry when the theme's scheme is already present", () => {
    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);
    // Corrupt one color, then re-apply: the entry must be corrected in place, not duplicated.
    write(read().replace('"background": "#0A0E14"', '"background": "#FFFFFF"'));

    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);
    const schemes = readWindowsTerminalSettings(settingsPath) as { schemes: { name: string }[] };
    expect(schemes.schemes.filter((s) => s.name === "Ghost Protocol")).toHaveLength(1);
  });

  it("collapses pre-existing duplicate entries for the theme's own scheme", () => {
    // The object merge filters out *every* entry with the name and appends one, so a file
    // holding two must come out holding one. The text path has to match that, or it leaves a
    // stale duplicate the merge promised was gone - and Windows Terminal honours whichever
    // duplicate it reads last, so the stale one is the one that wins.
    write(`{
  "profiles": { "defaults": {} },
  "schemes": [
    { "name": "Ghost Protocol", "background": "#AAAAAA" },
    // not mine, but keep it
    { "name": "Campbell", "background": "#0C0C0C" },
    { "name": "Ghost Protocol", "background": "#BBBBBB" }
  ]
}`);

    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);

    const schemes = readWindowsTerminalSettings(settingsPath).schemes as Record<string, unknown>[];
    expect(schemes.filter((s) => s.name === "Ghost Protocol")).toHaveLength(1);
    expect(schemes.find((s) => s.name === "Ghost Protocol")?.background).toBe("#0A0D0B");
    // The unrelated scheme and the comment attached to it are untouched by the de-duplication.
    expect(schemes.find((s) => s.name === "Campbell")?.background).toBe("#0C0C0C");
    expect(read()).toContain("// not mine, but keep it");
  });

  it("preserves a UTF-8 BOM and CRLF line endings", () => {
    // Notepad's "UTF-8 with BOM" plus CRLF: both are the editor's choice, not a defect, and a
    // write that dropped either would show up as a whole-file diff in the user's dotfiles repo.
    write("﻿" + COMMENTED_SETTINGS.replace(/\n/g, "\r\n"));

    expect(applyThemeFileOnly("ghost-protocol").ok).toBe(true);
    const after = read();
    expect(after.startsWith("﻿")).toBe(true);
    expect(after).toContain("\r\n");
    expect(after.replace(/\r\n/g, "")).not.toContain("\n");
  });
});
